import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { assertReleaseBuild, readBuildInfo } from "./build-info.ts";

const repo = mkdtempSync(join(tmpdir(), "threadpath-provenance-"));
const git = (...args: string[]): string => execFileSync("git", args, { cwd: repo, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
mkdirSync(join(repo, "apps", "desktop"), { recursive: true });
writeFileSync(join(repo, "apps", "desktop", "package.json"), JSON.stringify({ version: "0.1.0-beta.2" }));
assert.throws(() => assertReleaseBuild(readBuildInfo(repo)), /Git source provenance/);
git("init");
git("add", ".");
git("-c", "user.name=ThreadPath test", "-c", "user.email=test@example.invalid", "commit", "-m", "fixture");
const commit = git("rev-parse", "HEAD");
assert.deepEqual(readBuildInfo(repo), { version: "0.1.0-beta.2", commit, dirty: false, tag: null });
assert.throws(() => assertReleaseBuild(readBuildInfo(repo)), /requires tag/);
git("tag", "v0.1.0-beta.1");
assert.throws(() => assertReleaseBuild(readBuildInfo(repo)), /requires tag/);
git("-c", "user.name=ThreadPath test", "-c", "user.email=test@example.invalid", "tag", "-a", "v0.1.0-beta.2", "-m", "fixture release");
assertReleaseBuild(readBuildInfo(repo));
writeFileSync(join(repo, "untracked.txt"), "uncommitted");
assert.throws(() => assertReleaseBuild(readBuildInfo(repo)), /clean working tree/);
git("add", ".");
assert.throws(() => assertReleaseBuild(readBuildInfo(repo)), /clean working tree/);
git("-c", "user.name=ThreadPath test", "-c", "user.email=test@example.invalid", "commit", "-m", "different commit");
assert.throws(() => assertReleaseBuild(readBuildInfo(repo)), /requires tag/);
const nested = join(repo, "source-archive");
mkdirSync(join(nested, "apps", "desktop"), { recursive: true });
writeFileSync(join(nested, "apps", "desktop", "package.json"), JSON.stringify({ version: "0.1.0-beta.2" }));
assert.equal(readBuildInfo(nested).commit, null, "A source archive must not borrow its parent repository's commit");
console.log("[build-info] passed missing/unrelated Git, version mismatch, annotated tag, dirty tree and moved HEAD guards");
