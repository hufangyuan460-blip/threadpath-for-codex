import assert from "node:assert/strict";
import { mkdtemp, realpath } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { ThreadListItem } from "../shared/api.ts";
import { UserPreferencesService } from "./user-preferences.ts";
import { WorkspaceService, workspaceDisplayName } from "./workspace-service.ts";

async function main(): Promise<void> {
  // Windows CI can expose TEMP through an 8.3 alias; compare canonical paths.
  const root = await realpath(await mkdtemp(join(tmpdir(), "threadpath-workspaces-")));
  const first = join(root, "threadPath");
  const second = join(root, "another-project");
  const { mkdir } = await import("node:fs/promises");
  await mkdir(first);
  await mkdir(second);
  const preferences = new UserPreferencesService(join(root, "preferences.json"), "en-US");
  await preferences.load();
  const service = new WorkspaceService({ preferences });
  await service.addDirectory(first);
  await service.addDirectory(second);
  await service.associateThread("thread-a", first);
  await preferences.setThreadHidden("thread-a", true);
  await preferences.setWorkspaceHidden(first, true);
  await preferences.setThreadFavorite("thread-a", true);
  await preferences.setWorkspaceFavorite(first, true);
  const threads: ThreadListItem[] = [
    { id: "thread-a", title: "A", status: "active", turnCount: 1 },
    { id: "thread-b", title: "B", status: "active", turnCount: 2 },
  ];
  const state = await service.getState(threads);
  assert.ok(state.directories.every((directory) => !directory.expanded), "all initial projects are collapsed");
  assert.equal(state.currentPath, second);
  assert.deepEqual(state.directories.map((directory) => directory.name), ["threadPath", "another-project"]);
  assert.deepEqual(state.directories[0]?.threads.map((thread) => thread.id), ["thread-a"]);
  assert.equal(state.directories[0]?.hidden, true);
  assert.equal(state.directories[0]?.threads[0]?.hidden, true);
  assert.equal(state.directories[0]?.favorite, true);
  assert.equal(state.directories[0]?.threads[0]?.favorite, true);
  assert.deepEqual(state.unclassifiedThreads.map((thread) => thread.id), ["thread-b"]);
  await service.associateThread("thread-a", null);
  assert.deepEqual((await service.getState(threads)).unclassifiedThreads.map((thread) => thread.id), ["thread-a", "thread-b"]);
  await service.associateThread("thread-a", first);
  await service.setHidden(first, false);
  assert.equal((await service.getState(threads)).directories[0]?.hidden, undefined);
  await service.toggle(first);
  const manuallyExpanded = await service.getState(threads);
  assert.equal(manuallyExpanded.directories[0]?.expanded, true);
  assert.equal((await service.getState(threads, { state: "complete", threadCount: threads.length, missingThreadIds: [] })).directories[0]?.expanded, true, "background state refresh must retain expansion");
  await service.setCurrent(second);
  assert.equal((await service.getState(threads)).directories[0]?.expanded, true, "switching current project must retain expansion");
  preferences.collapseWorkspaces();
  const collapsed = await service.getState(threads);
  assert.ok(collapsed.directories.every((directory) => !directory.expanded));
  assert.deepEqual(collapsed.directories.map(({ expanded: _expanded, ...directory }) => directory), manuallyExpanded.directories.map(({ expanded: _expanded, ...directory }) => directory), "reset only affects expansion, not favorite/hidden/thread grouping");
  assert.equal(collapsed.currentPath, second);
  await service.toggle(first);
  await service.toggle(first);
  assert.equal((await service.getState(threads)).directories[0]?.expanded, false);
  const discovered = join(root, "new-synced-project");
  await mkdir(discovered);
  await service.identityResolver.resolve(discovered);
  await service.toggle(first);
  const withDiscovered = await service.getState([...threads, { id: "thread-c", title: "New history", status: "active", turnCount: 0, workspacePath: discovered }]);
  assert.equal(withDiscovered.directories.find((directory) => directory.path === discovered)?.expanded, false, "new history project defaults collapsed");
  assert.equal(withDiscovered.directories.find((directory) => directory.path === first)?.expanded, true, "discovering another project must not reset manual expansion");
  preferences.collapseWorkspaces();
  assert.equal(workspaceDisplayName(`${first}\\`), "threadPath");
  const standalone = join(root, "standalone-runtime");
  await mkdir(standalone);
  const standaloneService = new WorkspaceService({ preferences, standaloneDirectory: standalone, identityResolver: service.identityResolver });
  await standaloneService.setCurrent(null);
  assert.equal(await standaloneService.resolveSelection(standalone), standalone);
  await standaloneService.associateThread("thread-b", standalone);
  const standaloneState = await standaloneService.getState(threads);
  assert.equal(standaloneState.currentPath, standalone);
  assert.equal(standaloneState.standalonePath, standalone);
  assert.equal(standaloneState.directories.some((directory) => directory.path === standalone), false);
  assert.equal(standaloneState.configuredWorkspaces.some((workspace) => workspace.primaryDirectory === standalone), false);
  assert.deepEqual(standaloneState.unclassifiedThreads.map((thread) => thread.id), ["thread-b"]);
  const restoredPreferences = new UserPreferencesService(join(root, "preferences.json"), "en-US");
  await restoredPreferences.load();
  const restoredService = new WorkspaceService({ preferences: restoredPreferences, standaloneDirectory: standalone });
  assert.equal((await restoredService.getState(threads)).currentPath, standalone);
  await restoredService.setCurrent(first);
  assert.equal((await restoredService.getState(threads)).currentPath, first);
  console.log("[desktop-test] workspace service checks passed");
}

main().catch((error: unknown) => { console.error(`[desktop-test] FAILED: ${error instanceof Error ? error.message : String(error)}`); process.exitCode = 1; });
