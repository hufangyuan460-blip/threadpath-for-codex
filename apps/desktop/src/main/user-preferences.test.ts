import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { automaticThreadDisplayName, sanitizeThreadDisplayName, threadDisplayName, UserPreferencesService } from "./user-preferences.ts";

async function main(): Promise<void> {
  assert.equal(sanitizeThreadDisplayName("  <b>Hello</b>\nworld\u0000  "), "Hello world");
  assert.equal(sanitizeThreadDisplayName("abcdefghijklmnopqrstuvwxyz", 10), "abcdefghij");
  assert.equal(threadDisplayName({ customName: " Local ", firstUserText: "User", serverTitle: "Server", language: "en-US" }), "Local");
  assert.equal(automaticThreadDisplayName({ firstUserText: "<tool>\nAsk this", serverTitle: "Server", language: "zh-CN" }), "Ask this");
  assert.equal(automaticThreadDisplayName({ language: "zh-CN" }), "未命名会话");
  assert.equal(automaticThreadDisplayName({ language: "en-US" }), "Untitled conversation");

  const directory = await mkdtemp(join(tmpdir(), "threadpath-preferences-"));
  const path = join(directory, "preferences.json");
  const preferences = new UserPreferencesService(path, "en-US");
  await preferences.load();
  assert.equal(preferences.getLanguage(), "en-US");
  assert.equal(preferences.getWorkspaceExpanded(directory), false, "fresh workspaces start collapsed");
  await preferences.setWorkspaceExpanded(directory, true);
  assert.equal(preferences.getWorkspaceExpanded(directory), true);
  await preferences.setWorkspaceExpanded(directory, false);
  assert.equal(preferences.getWorkspaceExpanded(directory), false);
  await preferences.setLanguage("zh-CN");
  await preferences.setThreadDisplayName("thread-1", "My local name");
  assert.equal(preferences.getThreadDisplayName("thread-1", "Server"), "My local name");
  const reloaded = new UserPreferencesService(path, "en-US");
  await reloaded.load();
  assert.equal(reloaded.getLanguage(), "zh-CN");
  assert.equal(reloaded.getThreadDisplayName("thread-1", "Server"), "My local name");
  await reloaded.setThreadDisplayName("thread-1", null);
  assert.equal(reloaded.getThreadDisplayName("thread-1", "Server"), "Server");
  await reloaded.setThreadDisplayName("thread-2", "stale");
  await reloaded.setThreadHidden("thread-1", true);
  await reloaded.setWorkspaceHidden("C:\\project", true);
  await reloaded.setThreadFavorite("thread-1", true);
  await reloaded.setWorkspaceFavorite("C:\\project", true);
  assert.equal(reloaded.isThreadHidden("thread-1"), true);
  assert.equal(reloaded.isWorkspaceHidden("C:\\project"), true);
  assert.equal(reloaded.isThreadFavorite("thread-1"), true);
  assert.equal(reloaded.isWorkspaceFavorite("C:\\project"), true);
  await reloaded.pruneThreadNames(["thread-1"]);
  assert.equal(reloaded.getThreadDisplayName("thread-2", "Server"), "Server");
  assert.equal(reloaded.isThreadHidden("thread-1"), true);
  await reloaded.setThreadHidden("thread-1", false);
  await reloaded.setWorkspaceHidden("C:\\project", false);
  await reloaded.setThreadsHidden(["thread-1"], true);
  assert.equal(reloaded.isThreadHidden("thread-1"), true);
  await reloaded.setThreadsHidden(["thread-1"], false);
  await reloaded.setThreadFavorite("thread-1", false);
  await reloaded.setWorkspaceFavorite("C:\\project", false);
  assert.equal(reloaded.isThreadHidden("thread-1"), false);
  assert.equal(reloaded.isWorkspaceHidden("C:\\project"), false);
  assert.equal(reloaded.isThreadFavorite("thread-1"), false);
  assert.equal(reloaded.isWorkspaceFavorite("C:\\project"), false);
  await reloaded.recordBranch({ threadId: "branch-1", sourceThreadId: "thread-1", forkTurnId: "turn-1", forkLabel: "Explore another approach", createdAt: "2026-10-12T00:00:00Z", readOnly: true }, { id: "branch-1", cwd: "C:\\project", forkedFromId: "thread-1", sessionId: "branch-1" }, "Branch 1");
  await Promise.all([reloaded.setThreadDraft("thread-1", "source draft"), reloaded.setThreadDraft("branch-1", "first"), reloaded.setThreadDraft("branch-1", "last draft")]);
  await reloaded.flush();
  const restarted = new UserPreferencesService(path, "en-US");
  await restarted.load();
  assert.equal(restarted.getThreadDraft("branch-1"), "last draft", "concurrent saves must retain the latest draft");
  assert.equal(restarted.getThreadDraft("thread-1"), "source draft");
  assert.equal(restarted.getBranch("branch-1")?.forkTurnId, "turn-1");
  assert.equal(restarted.getThreadDisplayName("branch-1"), "Branch 1");
  assert.deepEqual(new Set(restarted.getRetainedThreadIds()), new Set(["branch-1", "thread-1"]));
  await restarted.setThreadWorkingDirectory("new-not-indexed", "C:\\project");
  const newReload = new UserPreferencesService(path, "en-US");
  await newReload.load();
  assert.ok(newReload.getRetainedThreadIds().includes("new-not-indexed"), "local workspace associations must retain new conversations across restart");
  await restarted.setThreadDraft("branch-1", "");
  assert.equal(restarted.getThreadDraft("branch-1"), "");
  await assert.rejects(restarted.setThreadDraft("branch-1", "x".repeat(100_001)), /at most/);
  const malformedPath = join(directory, "malformed.json");
  await writeFile(malformedPath, JSON.stringify({ language: "zh-CN", threadNames: { existing: "Keep me" }, threadBranches: { broken: { threadId: "broken" } }, threadDrafts: { " bad ": "invalid", good: "valid" } }));
  const malformed = new UserPreferencesService(malformedPath, "en-US");
  await malformed.load();
  assert.equal(malformed.getThreadDisplayName("existing"), "Keep me");
  assert.equal(malformed.getLanguage(), "zh-CN");
  assert.deepEqual(malformed.getBranches(), []);
  assert.equal(malformed.getThreadDraft("good"), "valid");
  const legacyPath = join(directory, "legacy-expansion.json");
  const project = join(directory, "project"), otherProject = join(directory, "other");
  const legacy = {
    expandedWorkingDirectories: { [project]: true, [otherProject]: false },
    workingDirectories: [project, otherProject], currentWorkingDirectory: project,
    hiddenWorkingDirectories: { [otherProject]: true }, favoriteWorkingDirectories: { [project]: true },
    threadDrafts: { existing: "keep this draft" },
    threadBranches: { child: { threadId: "child", sourceThreadId: "existing", forkTurnId: "turn-1", forkLabel: "Keep branch", createdAt: "2026-10-12T00:00:00Z", readOnly: true } },
  };
  await writeFile(legacyPath, JSON.stringify(legacy));
  const session = new UserPreferencesService(legacyPath, "en-US");
  await session.load();
  assert.equal(session.getWorkspaceExpanded(project), false, "legacy true must not reopen a workspace");
  assert.equal(session.getWorkspaceExpanded(otherProject), false);
  const beforeExpansion = await readFile(legacyPath, "utf8");
  await session.setWorkspaceExpanded(project, true);
  await session.setWorkspaceExpanded(otherProject, true);
  assert.equal(session.getWorkspaceExpanded(project), true);
  assert.equal(session.getWorkspaceExpanded(join(directory, "new-project")), false, "newly discovered paths start collapsed");
  assert.equal(session.getWorkspaceExpanded(project), true, "ordinary preference reads retain manual expansion");
  await session.flush();
  assert.equal(await readFile(legacyPath, "utf8"), beforeExpansion, "expansion must not write preferences");
  session.collapseWorkspaces();
  assert.equal(session.getWorkspaceExpanded(project), false);
  assert.equal(session.getWorkspaceExpanded(otherProject), false);
  assert.equal(session.getCurrentWorkingDirectory(), project);
  assert.equal(session.isWorkspaceFavorite(project), true);
  assert.equal(session.isWorkspaceHidden(otherProject), true);
  assert.equal(session.getThreadDraft("existing"), "keep this draft");
  assert.equal(session.getBranch("child")?.forkTurnId, "turn-1");
  assert.equal(await readFile(legacyPath, "utf8"), beforeExpansion, "collapse must not delete legacy values or other data");
  await session.setWorkspaceExpanded(project, true);
  await session.setLanguage("zh-CN");
  const savedLegacy = JSON.parse(await readFile(legacyPath, "utf8"));
  assert.deepEqual(savedLegacy.expandedWorkingDirectories, legacy.expandedWorkingDirectories, "unrelated saves preserve legacy data");
  const newSession = new UserPreferencesService(legacyPath, "en-US");
  await newSession.load();
  assert.equal(newSession.getWorkspaceExpanded(project), false, "restart discards manual expansion even if legacy true remains");
  assert.equal(newSession.getWorkspaceExpanded(otherProject), false);
  assert.equal(newSession.getCurrentWorkingDirectory(), project);
  assert.equal(newSession.getThreadDraft("existing"), "keep this draft");
  assert.equal(newSession.isWorkspaceFavorite(project), true);
  assert.equal(newSession.isWorkspaceHidden(otherProject), true);
  assert.equal(newSession.getBranch("child")?.forkTurnId, "turn-1");
  const saved = await readFile(path, "utf8");
  assert.ok(!saved.includes("token"));
  console.log("[desktop-test] user preference checks passed");
}

main().catch((error: unknown) => { console.error(`[desktop-test] FAILED: ${error instanceof Error ? error.message : String(error)}`); process.exitCode = 1; });
